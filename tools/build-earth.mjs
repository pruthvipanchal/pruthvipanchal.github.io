// Builds assets/js/earth-data.js, which says which dots of the hero's dotted Earth are land.
// Usage: node tools/build-earth.mjs <ne_110m_land.geojson> assets/js/earth-data.js
// The land outlines come from Natural Earth (public domain): https://www.naturalearthdata.com
// (file: geojson/ne_110m_land.geojson in github.com/nvkelso/natural-earth-vector).
import { readFileSync, writeFileSync } from 'node:fs';

const [src, out] = process.argv.slice(2);
const N = 20000; // dots on the whole sphere, evenly spaced (a Fibonacci sphere)

const land = JSON.parse(readFileSync(src, 'utf8'));
const polygons = land.features
  .flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates))
  .map((rings) => {
    const lons = rings[0].map((p) => p[0]);
    const lats = rings[0].map((p) => p[1]);
    return { rings, box: [Math.min(...lons), Math.min(...lats), Math.max(...lons), Math.max(...lats)] };
  });

// Ray casting in longitude/latitude. A point is land when an odd number of a polygon's rings
// contain it, so lakes cut out of a polygon stay water.
function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const isLand = (lon, lat) => polygons.some(({ rings, box }) =>
  lon >= box[0] && lon <= box[2] && lat >= box[1] && lat <= box[3]
  && rings.filter((ring) => inRing(lon, lat, ring)).length % 2 === 1);

// Dot i sits at (x, y, z) = (r cos t, y, r sin t); main.js rebuilds the same sphere.
// Latitude is asin(y) and longitude atan2(x, z), east positive.
const golden = Math.PI * (3 - Math.sqrt(5));
const bits = new Uint8Array(Math.ceil(N / 8));
let count = 0;
for (let i = 0; i < N; i++) {
  const y = 1 - ((i + 0.5) * 2) / N;
  const r = Math.sqrt(1 - y * y);
  const t = golden * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = (Math.atan2(r * Math.cos(t), r * Math.sin(t)) * 180) / Math.PI;
  if (isLand(lon, lat)) { bits[i >> 3] |= 1 << (i & 7); count++; }
}

const header = `/* Land mask for the dotted Earth, generated by tools/build-earth.mjs (do not edit by hand).
   Coastlines from Natural Earth (public domain, naturalearthdata.com).
   Format: n dots on a Fibonacci sphere; bit i of the base64 string \`land\` (least significant
   bit first) is set when dot i is on land. */\n`;
writeFileSync(out, `${header}window.PU_EARTH = ${JSON.stringify({ n: N, land: Buffer.from(bits).toString('base64') })};\n`);
console.log(`${count} of ${N} dots are land (${((100 * count) / N).toFixed(1)}%)`);
